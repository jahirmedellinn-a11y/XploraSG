// Los roles son datos (se guardan en español); sólo se traduce la etiqueta visible.
const ROLE_EN: Record<string, string> = {
  turista: 'Tourist',
  prestador: 'Local business',
  administrador: 'Administrator',
};

export const roleLabel = (rol: string | null | undefined, lang: Lang): string => {
  if (!rol) return '';
  return lang === 'en' ? ROLE_EN[rol] ?? rol : rol;
};
