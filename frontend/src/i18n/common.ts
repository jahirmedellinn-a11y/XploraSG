const CATEGORY_EN: Record<string, string> = {
  'Naturaleza': 'Nature',
  'Cultura y Arqueología': 'Culture & Archaeology',
  'Aventura': 'Adventure',
  'Gastronomía': 'Food & Drink',
  'Hospedaje': 'Lodging',
  'Servicios Comunitarios': 'Community Services',
};

export const categoryLabel = (name: string | null | undefined, lang: Lang): string => {
  if (!name) return '';
  return lang === 'en' ? CATEGORY_EN[name] ?? name : name;
};
